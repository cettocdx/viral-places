#!/usr/bin/env node
// Tek kaynak: config/design-tokens.json -> packages/design-tokens/src/tokens.generated.ts
// Elle düzenleme yapılmaz; test dosyası JSON ile üretilen TS'nin aynı olduğunu doğrular.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'config/design-tokens.json');
const target = resolve(root, 'packages/design-tokens/src/tokens.generated.ts');
const json = JSON.parse(readFileSync(source, 'utf8'));
const body = `// AUTO-GENERATED by scripts/sync-design-tokens.mjs from config/design-tokens.json
// Do not edit by hand. Run: pnpm tokens:sync
export const designTokens = ${JSON.stringify(json, null, 2)} as const;
`;
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== body) {
    console.error('design tokens out of sync: run pnpm tokens:sync');
    process.exit(1);
  }
  console.log('design tokens in sync');
} else {
  writeFileSync(target, body);
  console.log(`wrote ${target}`);
}
